/// ### 高精度定朔
///
/// 根据日月黄经差反推合朔（农历初一）的精确时刻。
///
/// **调用注意：**
/// * **累计弧度 [w]**：这是合朔的档位。0 是 J2000 附近的合朔，2π 是下一个月，以此类推。
/// * **返回值**：北京时间 (J2000 相对天数)。内部已自动扣除 ΔT 并加了 8 小时偏移。
/// * **精度说明**：这是基于底层星历模型的完整计算，精度最高，适合算具体的合朔秒数。
double soAccurate(double w) {
  // msALonT 是月球对应的星历反算函数
  final t = msALonT(w) * 36525.0;
  return t - dtT(t) + 8 / 24;
}

/// ### 智能定朔搜索
///
/// 根据给定的日期 [jd]，自动寻找并计算该月精确的合朔（初一）时刻。
///
/// **核心逻辑：**
/// * **相位对齐 (jd + 8)**：J2000 历元（2000-01-01）距离上一次合朔大约差了 8 天。加上这个偏移量，才能确保 `floor` 算出来的是正确的累计月份序号。
/// * **月数转弧度**：将估算的月份序号乘以 `2 * pi`，得到 `soAccurate` 需要的累计弧度 [w]。
/// * **返回值**：北京时间 (J2000 相对天数)。
double soAccurate2(double jd) {
  // 29.5306 是平均朔望月的长度
  final w = ((jd + 8) / 29.5306).floor() * 2 * pi;
  return soAccurate(w);
}

/// ### 获取指定年份的特定节气时刻 (单点查询)
  ///
  /// 利用太阳视黄经模型直接推算特定节气，不生成全年历表。
  ///
  /// **参数约定：**
  /// * [year] 公历年份 (如 2026)。
  /// * [n] 节气序号 (0~23)，以**春分**为 0 起点：
  ///   - 0=春分, 1=清明 ... 18=冬至 (发生于当年)
  ///   - 19=小寒, 20=大寒, 21=立春, 22=雨水, 23=惊蛰 (发生于次年 1~3 月)
  ///
  /// **跨年物理修正：**
  /// 天文学轨道周期以 3 月的春分为起点。当查询 1~3 月的节气 (n >= 19) 时，
  /// 物理模型上属于“上一个天文年”的末尾。内部已作自动偏移处理。
  double getSpecificJieQi(int year, int n) {
    int astroYear = year;
    // 修正 1~3 月节气的天文纪年偏移
    if (n >= 19) {
      astroYear -= 1;
    }

    // 计算累计弧度: 
    // (astroYear - 2000) * 2 * pi -> 2000年起算的整圈数
    // n * (pi / 12) -> 当前圈内的局部节气偏移
    final w = (astroYear - 2000) * 2 * pi + n * (pi / 12);

    // 调用高精度定气，返回 J2000 相对天数 (北京时间)
    return qiAccurate(w);
  }